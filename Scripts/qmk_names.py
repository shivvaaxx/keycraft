#!/usr/bin/env python3
"""Generates Sources/KeycraftCore/QMK/QMKNames.generated.swift from a QMK checkout's quantum/keycodes.h.

Usage: Scripts/qmk_names.py ~/qmk_firmware
Keeps every keycode name (canonical and alias) so opened keymap.c files resolve the same way QMK compiles them.
"""
import pathlib, re, subprocess, sys

qmk = pathlib.Path(sys.argv[1]).expanduser()
src = (qmk / "quantum/keycodes.h").read_text()
rev = subprocess.run(["git", "-C", str(qmk), "log", "-1", "--format=%h"], capture_output=True, text=True).stdout.strip()

canon = {}   # name -> code
for name, value in re.findall(r"^\s+([A-Z_][A-Z0-9_]*)\s*=\s*(0x[0-9A-Fa-f]{4}),", src, re.M):
    if name.endswith("_MAX"):
        continue
    canon.setdefault(name, int(value, 16))
alias = {}
for name, target in re.findall(r"^\s+([A-Z_][A-Z0-9_]*)\s*=\s*([A-Z_][A-Z0-9_]*),", src, re.M):
    if target in canon:
        alias[name] = canon[target]
# Range bases (QK_MODS, QK_MOD_TAP, ...) share codes with real keys; keep only names that are a single key.
ranges = {"QK_BASIC", "QK_MODS", "QK_MOD_TAP", "QK_LAYER_TAP", "QK_LAYER_MOD", "QK_TO", "QK_MOMENTARY", "QK_DEF_LAYER",
          "QK_TOGGLE_LAYER", "QK_ONE_SHOT_LAYER", "QK_ONE_SHOT_MOD", "QK_LAYER_TAP_TOGGLE", "QK_PERSISTENT_DEF_LAYER",
          "QK_SWAP_HANDS", "QK_TAP_DANCE", "QK_MAGIC", "QK_MIDI", "QK_SEQUENCER", "QK_JOYSTICK", "QK_PROGRAMMABLE_BUTTON",
          "QK_AUDIO", "QK_STENO", "QK_MACRO", "QK_CONNECTION", "QK_LIGHTING", "QK_QUANTUM", "QK_KB", "QK_USER",
          "QK_UNICODE", "QK_UNICODEMAP", "QK_UNICODEMAP_PAIR", "QK_MOUSE"}
canon = {n: c for n, c in canon.items() if n not in ranges}

lines = [f"{c:04X} {n}" for n, c in sorted(canon.items(), key=lambda kv: (kv[1], kv[0]))]
lines += [f"{c:04X} {n} alias" for n, c in sorted(alias.items(), key=lambda kv: (kv[1], kv[0]))]
out = pathlib.Path(__file__).resolve().parent.parent / "Sources/KeycraftCore/QMK/QMKNames.generated.swift"
out.write_text(f"""// Generated by Scripts/qmk_names.py from qmk_firmware {rev} quantum/keycodes.h. Do not edit.
// Each line: hex code, name, and "alias" for QMK's shorter alternative names.

extension QMKNames {{
    static let source = \"\"\"
{chr(10).join(lines)}
\"\"\"
}}
""")
print(f"{len(canon)} names, {len(alias)} aliases -> {out}")
